#!/usr/bin/env python3
"""Build one topic hub ("Topic Map") note per approved tag (runs locally; costs no tokens).

Reads tags from _claude-tags.md (lines like "- `aviation` — what it covers") and writes
Topics/Topic - <tag>.md (both found at the vault root or in `_Obsidian Internal/`) listing every note carrying that tag, grouped by top-level
folder, with path-qualified wikilinks and each note's description. Hubs are OKF concepts
(type: Topic Map). A hub is rewritten only if its contents changed; a hand-edited hub
(marker removed) is left alone. Tags with no notes get no hub.

Usage:
  python build_hubs.py <vault> [--folder <vault-relative Topics folder>] [--markdown-links]
"""
import argparse
import datetime as dt
import os
import re
import sys
from urllib.parse import quote

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vaultlib import RESERVED, split_frontmatter, top_folder, vault_path, vault_rel, walk

MARK = "<!-- generated by vault-librarian build_hubs.py; tag notes to change this list -->"
TAG_LINE = re.compile(r"^\s*[-*]\s*`?#?([\w/\-]+)`?\s*(?:[—–-]\s*(.*))?$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vault")
    ap.add_argument("--folder", default=None, help="default: Topics, at the root or in _Obsidian Internal")
    ap.add_argument("--markdown-links", action="store_true")
    a = ap.parse_args()
    vault = os.path.abspath(a.vault)
    a.folder = (a.folder or vault_rel(vault, "Topics")).replace("\\", "/").strip("/")
    tagfile = vault_path(vault, "_claude-tags.md")
    if not os.path.exists(tagfile):
        sys.exit("No _claude-tags.md at the vault root or in _Obsidian Internal — nothing to build.")
    _, _, body = split_frontmatter(open(tagfile, encoding="utf-8").read())
    tags = {}
    for ln in body.splitlines():
        m = TAG_LINE.match(ln)
        if m:
            tags[m.group(1).lower()] = (m.group(1), (m.group(2) or "").strip())
    members = {k: [] for k in tags}
    for rel, ab in walk(vault):
        if not rel.lower().endswith(".md") or rel.rsplit("/", 1)[-1] in RESERVED or rel.startswith(a.folder + "/"):
            continue
        with open(ab, encoding="utf-8", errors="replace") as f:
            fm, _, _ = split_frontmatter(f.read())
        fm = fm if isinstance(fm, dict) else {}
        nt = fm.get("tags") or []
        for t in (nt if isinstance(nt, list) else [nt]):
            k = str(t).lstrip("#").lower()
            if k in members:
                members[k].append((rel, str(fm.get("title") or rel.rsplit("/", 1)[-1][:-3]),
                                   str(fm.get("description") or "").strip(), str(fm.get("type") or "")))
    outdir = os.path.join(vault, *a.folder.split("/"))
    wrote = 0
    for k, (tag, desc) in sorted(tags.items()):
        items = sorted(members[k], key=lambda x: ((top_folder(x[0]) if "/" in x[0] else x[0]).lower(), x[1].lower()))
        if not items:
            continue
        lines = [MARK, "", f"# {tag}", ""]
        if desc:
            lines += [desc, ""]
        group = None
        for rel, title, d, typ in items:
            top = top_folder(rel)
            if top != group:
                lines += ["", f"## {top}", ""] if group is not None else [f"## {top}", ""]
                group = top
            ln = f"[{title}](/{quote(rel, safe='/-_.~')})" if a.markdown_links else f"[[{rel[:-3]}|{title}]]"
            lines.append(f"- {ln}" + (f" — {d}" if d else "") + (f" *({typ})*" if typ else ""))
        body_text = "\n".join(lines).rstrip() + "\n"
        path = os.path.join(outdir, f"Topic - {tag}.md")
        if os.path.exists(path):
            old = open(path, encoding="utf-8").read()
            if MARK not in old:
                print(f"skip (hand-edited): {a.folder}/Topic - {tag}.md")
                continue
            if split_frontmatter(old)[2].strip() == body_text.strip():
                continue
        at = dt.datetime.now().astimezone().isoformat(timespec="seconds")
        fm = (f'---\ntype: "Topic Map"\ntitle: "{tag}"\n'
              f'description: "Everything in the vault tagged {tag}' + (f' — {desc}' if desc else '') + '."\n'
              f'tags: ["{tag}"]\ngenerated: {{ by: "process:vault-librarian", at: "{at}" }}\n---\n\n')
        os.makedirs(outdir, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(fm + body_text)
        wrote += 1
        print(f"wrote {a.folder}/Topic - {tag}.md ({len(items)} notes)")
    print(f"{wrote} hubs written/updated")


if __name__ == "__main__":
    main()
