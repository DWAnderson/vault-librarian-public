#!/usr/bin/env python3
"""(Re)build OKF `index.md` files from note frontmatter (runs locally; costs no tokens).

Each folder gets an index.md listing its notes (title + description) and subfolders,
grouped by `type`. Only files this script created (marked with a comment) are
overwritten; a hand-written index.md is left alone unless --force.

Usage:
  python build_indexes.py <vault> [--folders Projects Areas ...] [--markdown-links] [--force]
Default link style is Obsidian [[wikilinks]] (the vault convention); okf_export.py
converts them. --markdown-links writes OKF-style [Title](/path.md) links instead.
"""
import argparse
import os
import sys
from urllib.parse import quote

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vaultlib import INTERNAL_DIR, RESERVED, SKIP_DIRS, split_frontmatter

MARK = "<!-- generated by vault-librarian build_indexes.py; edit notes' descriptions, not this file -->"
SKIP_TOP = {"Templates", "_templates", "attachments", "Attachments"}


def link(rel, title, md):
    if md:
        return f"[{title}](/{quote(rel, safe='/-_.~')})"
    # path-qualified wikilink: never ambiguous even if two notes share a name
    return f"[[{rel[:-3]}|{title}]]"


def build(vault, folder, md, force, root_version):
    ab = os.path.join(vault, *folder.split("/")) if folder else vault
    entries, subdirs = {}, []
    for name in sorted(os.listdir(ab), key=str.lower):
        p = os.path.join(ab, name)
        rel = f"{folder}/{name}" if folder else name
        if os.path.isdir(p):
            if name not in SKIP_DIRS and not name.startswith(".") and not ((not folder or folder.lower() == INTERNAL_DIR.lower()) and name in SKIP_TOP):
                subdirs.append(rel)
            continue
        if not name.lower().endswith(".md") or name in RESERVED:
            continue
        with open(p, encoding="utf-8", errors="replace") as f:
            fm, _, _ = split_frontmatter(f.read())
        fm = fm or {}
        title = str(fm.get("title") or name[:-3])
        desc = str(fm.get("description") or "").strip()
        entries.setdefault(str(fm.get("type") or "Untyped"), []).append((title, rel, desc))
    idx = os.path.join(ab, "index.md")
    if os.path.exists(idx) and not force:
        with open(idx, encoding="utf-8", errors="replace") as f:
            if MARK not in f.read():
                print(f"skip (hand-written): {folder or '/'}index.md")
                return subdirs
    title = folder.rsplit("/", 1)[-1] if folder else "Vault"
    lines = []
    if not folder and root_version:
        lines += ["---", f'okf_version: "{root_version}"', "---", ""]
    lines += [MARK, "", f"# {title}", ""]
    if subdirs:
        lines += ["## Folders", ""]
        for s in subdirs:
            label = s.rsplit("/", 1)[-1]
            lines.append(f"- [{label}](/{quote(s, safe='/-_.~')}/index.md)" if md else f"- [[{s}/index|{label}]]")
        lines.append("")
    for typ in sorted(entries, key=str.lower):
        lines += [f"## {typ}", ""]
        for t, rel, desc in entries[typ]:
            lines.append(f"- {link(rel, t, md)}" + (f" — {desc}" if desc else ""))
        lines.append("")
    with open(idx, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(f"wrote {folder + '/' if folder else ''}index.md ({sum(len(v) for v in entries.values())} notes)")
    return subdirs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vault")
    ap.add_argument("--folders", nargs="*", help="limit to these top-level folders (root index always rebuilt)")
    ap.add_argument("--markdown-links", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--okf-version", default="0.2")
    a = ap.parse_args()
    vault = os.path.abspath(a.vault)
    queue = build(vault, "", a.markdown_links, a.force, a.okf_version)
    if a.folders:
        queue = [q for q in queue if q in a.folders]
    while queue:
        queue = queue[1:] + build(vault, queue[0], a.markdown_links, a.force, a.okf_version)


if __name__ == "__main__":
    main()
